#!/usr/bin/env python3
"""
Linux System Hardening Automation

Applies a CIS-style baseline (sysctl, sshd, file permissions, unused services).

SAFE BY DEFAULT: without --apply the script only reports what it would change.

Dependencies:
    No external dependencies (stdlib only)

Usage:
    # Preview (default; no changes, root not required)
    python3 harden-linux.py

    # Audit current state (read-only)
    python3 harden-linux.py --audit

    # Apply everything except SSH auth changes
    sudo python3 harden-linux.py --apply --skip-ssh

    # Apply including SSH, after proving key login works in a SECOND session
    sudo python3 harden-linux.py --apply --confirm-key-login

    # Also disable IP forwarding (only on hosts that are NOT container hosts,
    # Kubernetes nodes, routers or VPN gateways)
    sudo python3 harden-linux.py --apply --disable-ip-forward

SSH lockout safeguards (applied when --apply touches sshd):
    1. Refuses unless --confirm-key-login is given (you verified key login in a
       second, still-open session).
    2. Refuses if the invoking user has no non-empty authorized_keys file.
    3. Writes /etc/ssh/sshd_config.d/00-hardening.conf (sshd uses the FIRST value
       it reads, so 00- sorts before 50-cloud-init.conf and wins).
    4. Runs `sshd -t`; on failure the previous file is restored and nothing is
       reloaded.
    5. Reloads the detected unit (ssh.service on Debian/Ubuntu, sshd.service
       elsewhere) with try-reload-or-restart; existing sessions stay open.
    6. Re-reads the effective config with `sshd -T` and reports any setting that
       an earlier config line still overrides.
"""

import argparse
import os
import pwd
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Dict, List, Optional

SYSCTL_SETTINGS: Dict[str, str] = {
    "kernel.randomize_va_space": "2",
    "kernel.kptr_restrict": "2",
    "kernel.dmesg_restrict": "1",
    "kernel.yama.ptrace_scope": "2",
    "net.ipv4.conf.all.accept_redirects": "0",
    "net.ipv4.conf.all.send_redirects": "0",
    "net.ipv4.tcp_syncookies": "1",
    "net.ipv4.conf.all.accept_source_route": "0",
    "net.ipv4.conf.all.rp_filter": "1",
    "fs.protected_hardlinks": "1",
    "fs.protected_symlinks": "1",
    "fs.suid_dumpable": "0",
}

# Only applied with --disable-ip-forward: breaks Docker/Podman/Kubernetes
# networking, routers and VPN gateways.
IP_FORWARD_SETTINGS: Dict[str, str] = {
    "net.ipv4.ip_forward": "0",
    "net.ipv6.conf.all.forwarding": "0",
}

SSH_CONFIG = """# SSH Hardening Configuration
# Generated by harden-linux.py. Named 00-* so it sorts first: sshd keeps the
# FIRST value it reads for most keywords.

# Authentication
PermitRootLogin no
PasswordAuthentication no
PermitEmptyPasswords no
KbdInteractiveAuthentication no
PubkeyAuthentication yes
MaxAuthTries 3

# Encryption
KexAlgorithms curve25519-sha256,curve25519-sha256@libssh.org
Ciphers chacha20-poly1305@openssh.com,aes256-gcm@openssh.com,aes128-gcm@openssh.com
MACs hmac-sha2-512-etm@openssh.com,hmac-sha2-256-etm@openssh.com

# Session Security (port forwarding is left at the distro default because
# operators often rely on tunnels; set AllowTcpForwarding no if you do not)
X11Forwarding no
AllowAgentForwarding no
ClientAliveInterval 300
ClientAliveCountMax 2

# Logging
LogLevel VERBOSE
"""

# Effective values (lower-case, as printed by `sshd -T`) checked after reload.
SSH_EXPECTED = {
    "permitrootlogin": "no",
    "passwordauthentication": "no",
    "pubkeyauthentication": "yes",
    "x11forwarding": "no",
}

CONTAINER_OR_ROUTER_MARKERS = [
    "/var/run/docker.sock",
    "/run/podman",
    "/run/containerd/containerd.sock",
    "/etc/kubernetes",
    "/var/lib/kubelet",
    "/etc/cni/net.d",
    "/etc/wireguard",
]


def run(cmd: List[str], **kwargs) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, capture_output=True, text=True, **kwargs)


class LinuxHardener:
    """Automates Linux system hardening based on CIS benchmarks."""

    sysctl_file = Path("/etc/sysctl.d/99-hardening.conf")
    ssh_dropin_dir = Path("/etc/ssh/sshd_config.d")
    ssh_dropin_name = "00-hardening.conf"
    ssh_main_config = Path("/etc/ssh/sshd_config")

    def __init__(self, apply: bool = False):
        self.apply = apply
        self.changes: List[str] = []
        self.warnings: List[str] = []
        self.errors: List[str] = []

    def _plan(self, msg: str) -> None:
        self.changes.append(msg if self.apply else f"[DRY RUN] Would {msg[0].lower()}{msg[1:]}")

    # ---------------------------------------------------------------- sysctl
    def apply_sysctl(self, settings: Dict[str, str]) -> None:
        """Write and load kernel parameters."""
        content = "# Security hardening parameters\n# Generated by harden-linux.py\n\n"
        content += "".join(f"{k} = {v}\n" for k, v in settings.items())

        if not self.apply:
            self._plan(f"Write {self.sysctl_file} with {len(settings)} settings and run sysctl --system")
            for k, v in settings.items():
                self.changes.append(f"[DRY RUN]   {k} = {v}")
            return
        try:
            self.sysctl_file.write_text(content)
            subprocess.run(["sysctl", "--system"], check=True, capture_output=True)
            self._plan(f"Applied {len(settings)} sysctl settings")
        except Exception as e:
            self.errors.append(f"Failed to apply sysctl: {e}")

    # ------------------------------------------------------------------- ssh
    @staticmethod
    def detect_ssh_unit() -> Optional[str]:
        """Return the sshd systemd unit name (ssh.service on Debian/Ubuntu)."""
        for unit in ("ssh.service", "sshd.service"):
            try:
                r = run(["systemctl", "show", "-p", "LoadState", "--value", unit], timeout=5)
            except Exception:
                return None
            if r.stdout.strip() == "loaded":
                return unit
        return None

    @staticmethod
    def invoking_user() -> str:
        return os.environ.get("SUDO_USER") or pwd.getpwuid(os.getuid()).pw_name

    @staticmethod
    def has_authorized_keys(user: str) -> bool:
        try:
            home = Path(pwd.getpwnam(user).pw_dir)
        except KeyError:
            return False
        for name in ("authorized_keys", "authorized_keys2"):
            f = home / ".ssh" / name
            try:
                if any(l.strip() and not l.lstrip().startswith("#") for l in f.read_text().splitlines()):
                    return True
            except OSError:
                continue
        return False

    def main_config_includes_dropins(self) -> bool:
        try:
            text = self.ssh_main_config.read_text()
        except OSError:
            return False
        return any(
            l.strip().lower().startswith("include") and "sshd_config.d" in l
            for l in text.splitlines()
        )

    def ssh_preflight(self, confirm_key_login: bool) -> bool:
        """Return True only if it is safe to disable password logins."""
        ok = True
        user = self.invoking_user()
        if not self.has_authorized_keys(user):
            (self.errors if self.apply else self.warnings).append(
                f"SSH: no non-empty ~{user}/.ssh/authorized_keys; disabling password auth could lock you out. "
                "Install a key (ssh-copy-id) first, or rerun with --skip-ssh."
            )
            ok = False
        if not confirm_key_login:
            msg = (
                "SSH: not confirmed. From another terminal run "
                "`ssh -o PreferredAuthentications=publickey -o PasswordAuthentication=no <user>@<host>`, "
                "keep that session open, then rerun with --confirm-key-login."
            )
            (self.errors if self.apply else self.warnings).append(msg)
            ok = False
        if not self.main_config_includes_dropins():
            self.warnings.append(
                f"SSH: {self.ssh_main_config} has no 'Include /etc/ssh/sshd_config.d/*.conf'; "
                "the drop-in would be ignored. Add the Include line at the TOP of sshd_config."
            )
        if self.detect_ssh_unit() is None:
            self.warnings.append("SSH: could not find ssh.service or sshd.service; reload sshd manually.")
        return ok

    def harden_ssh(self, confirm_key_login: bool) -> None:
        """Apply SSH hardening with lockout safeguards."""
        target = self.ssh_dropin_dir / self.ssh_dropin_name
        safe = self.ssh_preflight(confirm_key_login)

        if not self.apply:
            unit = self.detect_ssh_unit() or "<ssh unit>"
            self._plan(f"Write {target}, run `sshd -t`, then `systemctl try-reload-or-restart {unit}`")
            return
        if not safe:
            self.errors.append("SSH hardening skipped (preflight failed); nothing in /etc/ssh was changed.")
            return

        backup: Optional[str] = None
        try:
            self.ssh_dropin_dir.mkdir(parents=True, exist_ok=True)
            if target.exists():
                backup = target.read_text()
            target.write_text(SSH_CONFIG)
            os.chmod(target, 0o600)

            test = run(["sshd", "-t"])
            if test.returncode != 0:
                self._restore(target, backup)
                self.errors.append(f"`sshd -t` failed, previous config restored: {test.stderr.strip()}")
                return

            unit = self.detect_ssh_unit()
            if unit:
                subprocess.run(["systemctl", "try-reload-or-restart", unit], check=True)
                self._plan(f"Applied SSH hardening ({target}) and reloaded {unit}")
            else:
                self.warnings.append(f"Wrote {target} but could not detect the ssh unit; reload it manually.")

            effective = self.effective_ssh_config()
            for key, want in SSH_EXPECTED.items():
                got = effective.get(key)
                if got != want:
                    self.warnings.append(
                        f"SSH: effective {key} is {got!r}, expected {want!r}; an earlier line in "
                        f"{self.ssh_main_config} or a lower-sorting drop-in overrides it."
                    )
            self.warnings.append(
                "SSH: open a NEW key-based session now and confirm it works before closing the old one."
            )
        except Exception as e:
            self._restore(target, backup)
            self.errors.append(f"Failed to apply SSH hardening (previous config restored): {e}")

    @staticmethod
    def _restore(target: Path, backup: Optional[str]) -> None:
        try:
            if backup is None:
                target.unlink(missing_ok=True)
            else:
                target.write_text(backup)
        except OSError:
            pass

    @staticmethod
    def effective_ssh_config() -> Dict[str, str]:
        try:
            r = run(["sshd", "-T"], timeout=5)
        except Exception:
            return {}
        out: Dict[str, str] = {}
        for line in r.stdout.lower().splitlines():
            parts = line.split(None, 1)
            if len(parts) == 2:
                out.setdefault(parts[0], parts[1].strip())
        return out

    # ----------------------------------------------------------- permissions
    def set_file_permissions(self) -> None:
        """Set secure permissions on critical files."""
        # (max mode, force root:root). Modes are only ever tightened. /etc/shadow
        # and /etc/gshadow keep their group: Debian/Ubuntu ship 640 root:shadow and
        # unix_chkpwd (screen lockers, sudo prompts) needs that group read bit.
        permissions = {
            "/etc/ssh/sshd_config": (0o600, True),
            "/etc/shadow": (0o640, False),
            "/etc/gshadow": (0o640, False),
            "/etc/crontab": (0o600, True),
            "/etc/cron.d": (0o700, True),
            "/etc/cron.daily": (0o700, True),
            "/etc/cron.hourly": (0o700, True),
            "/etc/cron.monthly": (0o700, True),
            "/etc/cron.weekly": (0o700, True),
        }
        for file_path, (max_mode, force_root) in permissions.items():
            path = Path(file_path)
            if not path.exists():
                continue
            current = path.stat().st_mode & 0o777
            target = current & max_mode
            if target == current:
                continue
            owner = " (root:root)" if force_root else ""
            if not self.apply:
                self._plan(f"Chmod {file_path} {current:o} -> {target:o}{owner}")
                continue
            try:
                os.chmod(path, target)
                if force_root:
                    os.chown(path, 0, 0)
                self._plan(f"Set permissions {target:o} on {file_path}")
            except Exception as e:
                self.errors.append(f"Failed to set permissions on {file_path}: {e}")

    # -------------------------------------------------------------- services
    def disable_services(self, services: List[str]) -> None:
        """Disable unnecessary services that are currently enabled."""
        for service in services:
            try:
                state = run(["systemctl", "is-enabled", service], timeout=5).stdout.strip()
            except Exception:
                continue
            if state != "enabled":  # note: "disabled" contains "enabled"
                continue
            if not self.apply:
                self._plan(f"Disable and stop {service}")
                continue
            try:
                subprocess.run(["systemctl", "disable", "--now", service], check=True)
                self._plan(f"Disabled service: {service}")
            except Exception as e:
                self.errors.append(f"Failed to disable {service}: {e}")

    # ----------------------------------------------------------------- audit
    def audit(self, check_ip_forward: bool = False) -> Dict[str, bool]:
        """Audit current hardening status (read-only)."""
        ssh = self.effective_ssh_config()
        results = {
            "ssh_root_login": ssh.get("permitrootlogin") == "no",
            "ssh_password_auth": ssh.get("passwordauthentication") == "no",
            "aslr_enabled": self._check_sysctl("kernel.randomize_va_space", "2"),
            "syn_cookies_enabled": self._check_sysctl("net.ipv4.tcp_syncookies", "1"),
            "shadow_permissions": self._check_file_mode("/etc/shadow", (0o600, 0o640, 0o000)),
            "sshd_config_permissions": self._check_file_mode("/etc/ssh/sshd_config", (0o600,)),
        }
        if check_ip_forward:
            results["ip_forward_disabled"] = self._check_sysctl("net.ipv4.ip_forward", "0")
        return results

    @staticmethod
    def _check_sysctl(key: str, expected: str) -> bool:
        try:
            return run(["sysctl", "-n", key], timeout=5).stdout.strip() == expected
        except Exception:
            return False

    @staticmethod
    def _check_file_mode(path: str, allowed: tuple) -> bool:
        try:
            return (Path(path).stat().st_mode & 0o777) in allowed
        except OSError:
            return False


def forwarding_host_markers() -> List[str]:
    found = [m for m in CONTAINER_OR_ROUTER_MARKERS if Path(m).exists()]
    for binary in ("docker", "podman", "kubelet", "k3s"):
        if shutil.which(binary):
            found.append(binary)
    return found


def main():
    parser = argparse.ArgumentParser(
        description="Linux System Hardening Automation (dry run unless --apply is given)"
    )
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--apply", action="store_true", help="Actually change the system (requires root)")
    mode.add_argument("--dry-run", action="store_true", help="Preview only (this is the default)")
    mode.add_argument("--audit", action="store_true", help="Audit current hardening status")
    parser.add_argument("--skip-ssh", action="store_true", help="Do not touch sshd configuration")
    parser.add_argument(
        "--confirm-key-login",
        action="store_true",
        help="Confirm you verified key-based SSH login in a second, still-open session",
    )
    parser.add_argument(
        "--disable-ip-forward",
        action="store_true",
        help="Also set ip_forward=0 (NOT for container hosts, Kubernetes nodes, routers or VPN gateways)",
    )
    parser.add_argument(
        "--force-ip-forward",
        action="store_true",
        help="With --disable-ip-forward: proceed even if container/router markers are detected",
    )
    args = parser.parse_args()

    hardener = LinuxHardener(apply=args.apply)

    if args.audit:
        print("=== Linux Hardening Audit ===\n")
        results = hardener.audit(check_ip_forward=args.disable_ip_forward)
        for check, passed in results.items():
            print(f"{'PASS' if passed else 'FAIL'}: {check}")
        passed_count = sum(results.values())
        print(f"\nScore: {passed_count}/{len(results)} ({passed_count / len(results) * 100:.1f}%)")
        sys.exit(0 if passed_count == len(results) else 1)

    if args.apply and os.geteuid() != 0:
        print("ERROR: --apply must be run as root (use sudo)")
        sys.exit(1)

    print("=== Linux System Hardening ===")
    print("Mode: APPLY\n" if args.apply else "Mode: DRY RUN (no changes; rerun with --apply to change the system)\n")

    sysctl = dict(SYSCTL_SETTINGS)
    if args.disable_ip_forward:
        markers = forwarding_host_markers()
        if markers and not args.force_ip_forward:
            hardener.errors.append(
                "Refusing --disable-ip-forward: this looks like a container/Kubernetes/VPN host "
                f"({', '.join(markers)}); ip_forward=0 would break its networking. "
                "Use --force-ip-forward only if you are sure."
            )
        else:
            sysctl.update(IP_FORWARD_SETTINGS)

    print("[1/4] Kernel parameters...")
    hardener.apply_sysctl(sysctl)

    print("[2/4] SSH hardening...")
    if args.skip_ssh:
        print("      skipped (--skip-ssh)")
    else:
        hardener.harden_ssh(confirm_key_login=args.confirm_key_login)

    print("[3/4] File permissions...")
    hardener.set_file_permissions()

    print("[4/4] Unnecessary services...")
    hardener.disable_services(["bluetooth.service", "cups.service", "avahi-daemon.service"])

    print("\n=== Summary ===")
    label = "Changes applied" if args.apply else "Planned changes"
    print(f"\n{label}: {len(hardener.changes)}")
    for change in hardener.changes:
        print(f"  - {change}")
    if hardener.warnings:
        print(f"\nWarnings: {len(hardener.warnings)}")
        for w in hardener.warnings:
            print(f"  ! {w}")
    if hardener.errors:
        print(f"\nErrors: {len(hardener.errors)}")
        for e in hardener.errors:
            print(f"  x {e}")
        sys.exit(1)

    if not args.apply:
        print("\nNothing was changed. Review the plan, then rerun with sudo and --apply.")
        return
    print("\nNext steps:")
    print(f"  1. Review {LinuxHardener.sysctl_file}")
    print(f"  2. Review {LinuxHardener.ssh_dropin_dir / LinuxHardener.ssh_dropin_name}")
    print("  3. Confirm a NEW key-based SSH login works before closing your current session")
    print("  4. Run: python3 harden-linux.py --audit")


if __name__ == "__main__":
    main()
